#!/usr/bin/env bash
# generate.sh — assemble a generated quant repo from the THREE pinned tags. This is what the
# Backstage scaffolder / Copier does in production; here it is a plain script so we can run it
# on this box. No symlinks: platform/ is materialized as REAL content from the pinned tag via
# `git archive` (works on Windows; identical to Copier's _preserve_symlinks: false).
#
#   generate.sh <name> <platform-tag> <pricers-tag> <method> [method...]
#   e.g. generate.sh quant-pricer4 platform-v1.0.0 pricers-v1.0.0 black_scholes bachelier
set -euo pipefail

name=${1:?usage: generate.sh <name> <platform-tag> <pricers-tag> <method...>}
ptag=${2:?missing platform tag}
rtag=${3:?missing pricers tag}
shift 3
methods=("$@")
[ ${#methods[@]} -ge 1 ] || { echo "need at least one method" >&2; exit 2; }

root=$(cd "$(dirname "$0")/.." && pwd)        # xp-split root (xp-backstage is one level down)
platform_repo="$root/xp-platform"
pricers_repo="$root/xp-pricer-templates"
dest="$root/generated/$name"

[ -e "$dest" ] && { echo "destination exists: $dest" >&2; exit 2; }
mkdir -p "$dest/platform"

# 1) REAL platform/, pinned to the tag (git archive => exactly the tagged tree).
git -C "$platform_repo" archive "$ptag" | tar -x -C "$dest/platform"

# 2) the chosen pricer folders, pinned to the pricers tag.
for m in "${methods[@]}"; do
  git -C "$pricers_repo" archive "$rtag" "pricers/$m" | tar -x -C "$dest"
done

# 3) root CMakeLists.txt — thin, PLATFORM-owned wiring only (guard 4d enforces this shape).
{
  echo "# ${name} — generated. PLATFORM-owned: only wiring, no build policy. Do not add flags here."
  echo "cmake_minimum_required(VERSION 3.25)"
  echo "list(APPEND CMAKE_MODULE_PATH \"\${CMAKE_CURRENT_SOURCE_DIR}/platform/cmake\")"
  echo "include(XpProject)"
  echo "xp_project(${name})"
  for m in "${methods[@]}"; do echo "add_subdirectory(pricers/${m})"; done
} > "$dest/CMakeLists.txt"

# 4) root CMakePresets.json — the ONLY presets file allowed outside platform/; just an include.
cat > "$dest/CMakePresets.json" <<JSON
{
  "version": 6,
  "include": ["platform/presets/CMakePresets.json"]
}
JSON

# 5) answers file — records BOTH pinned tags (Renovate + copier update read this).
cat > "$dest/.copier-answers.yml" <<YML
# Generated by xp-backstage. Do not edit by hand; run \`copier update\` to bump.
_src: xp-backstage
project_name: ${name}
platform_ref: ${ptag}
pricers_ref: ${rtag}
methods: [$(IFS=,; echo "${methods[*]}")]
YML

# 6) renovate.json — tracks the two platform tags so a new release opens a bump MR.
cat > "$dest/renovate.json" <<'JSON'
{
  "$schema": "https://docs.renovatebot.com/renovate-schema.json",
  "extends": ["config:recommended"],
  "regexManagers": [
    {
      "fileMatch": ["^\\.copier-answers\\.yml$"],
      "matchStrings": [
        "platform_ref:\\s*(?<currentValue>platform-v[0-9.]+)",
        "pricers_ref:\\s*(?<currentValue>pricers-v[0-9.]+)"
      ],
      "datasourceTemplate": "git-tags",
      "depNameTemplate": "xp-platform"
    }
  ]
}
JSON

# 7) generated-repo CODEOWNERS — platform/, CMakeLists, presets, CI, quarantine -> build-eng; pricers -> quants.
cat > "$dest/CODEOWNERS" <<'OWN'
# Generated repo ownership. Build machinery is build-eng's; pricer code is the quants'.
platform/                 @platform/build-eng
/CMakeLists.txt           @platform/build-eng
/CMakePresets.json        @platform/build-eng
/.gitlab-ci.yml           @platform/build-eng
/quarantine.txt           @platform/build-eng
pricers/                  @quant/quant-devs
OWN

# 7b) .gitlab-ci.yml — PLATFORM-owned. Every job comes from xp-platform components pinned to the
#     SAME tag as platform/, so a Renovate bump of platform_ref moves code and CI together.
sed "s/__PTAG__/${ptag}/g" > "$dest/.gitlab-ci.yml" <<'CI'
# .gitlab-ci.yml — generated by xp-backstage. PLATFORM-owned (CODEOWNERS): jobs come from the
# xp-platform components below, pinned to the same tag as platform/ (.copier-answers.yml).
# Do not add jobs here; change the components in xp-platform and bump the tag instead.
workflow:
  rules:
    # MR pipelines: read-only caches (unreviewed code never publishes cache entries).
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
      variables: { XP_CACHE_POLICY: pull, XP_VCPKG_CACHE_MODE: read, XP_BUDGET_MODE: check }
    - if: $CI_COMMIT_BRANCH && $CI_OPEN_MERGE_REQUESTS
      when: never
    - if: $CI_COMMIT_REF_PROTECTED == "true"
      variables: { XP_CACHE_POLICY: pull-push, XP_VCPKG_CACHE_MODE: readwrite, XP_BUDGET_MODE: record }
    - if: $CI_COMMIT_BRANCH || $CI_COMMIT_TAG
      variables: { XP_CACHE_POLICY: pull, XP_VCPKG_CACHE_MODE: read, XP_BUDGET_MODE: check }

stages: [build-test, review]

variables:
  XP_REGISTRY: registry.xp.internal
  # Airlocked images (ingested + scanned + signed into golden/); pin by digest once promoted.
  XP_LINUX_IMAGE: $XP_REGISTRY/golden/xp-toolchain:alma8-gcc13-clang17   # RHEL 8 userland, glibc 2.28
  XP_REVIEW_IMAGE: $XP_REGISTRY/golden/xp-ci-reviewer@sha256:7c7d231cd82ddcb6fcdd32856ebaf19b05f27e4e5d9b56e8f8d3fd903dd859b9   # python3 + git + semgrep 1.185
  GIT_FETCH_EXTRA_FLAGS: --tags   # GitVersion.cmake needs tags for `git describe`

include:
  # build-test: one job per preset (RedHat 8: gcc 13 and clang 17), in parallel
  - component: $CI_SERVER_FQDN/platform/xp-platform/cpp-build@__PTAG__
    inputs: { preset: ci-linux-gcc, image: $XP_LINUX_IMAGE, cache_key: vcpkg-x64-linux-rhel8-gcc13 }
  - component: $CI_SERVER_FQDN/platform/xp-platform/cpp-build@__PTAG__
    inputs: { preset: ci-linux-clang, image: $XP_LINUX_IMAGE, cache_key: vcpkg-x64-linux-rhel8-clang17 }
  # Windows and Ubuntu presets exist in platform/presets; enable once a Windows MSVC runner and an
  # Ubuntu toolchain image are available (not yet built or tested):
  # - component: $CI_SERVER_FQDN/platform/xp-platform/cpp-build@__PTAG__
  #   inputs: { preset: ci-win-msvc, image: $XP_WINDOWS_IMAGE, cache_key: vcpkg-x64-windows-v143-static-md, runner_tags: [windows, msvc], python: python }
  # - component: $CI_SERVER_FQDN/platform/xp-platform/cpp-build@__PTAG__
  #   inputs: { preset: ci-ubuntu-gcc, image: $XP_UBUNTU_IMAGE, cache_key: vcpkg-x64-linux-ubuntu-gcc }
  # review: rule-based MR review from the pinned platform tag (exit 87 review, 88 testreview)
  - component: $CI_SERVER_FQDN/platform/xp-platform/review@__PTAG__
    inputs: { platform_repo: $CI_SERVER_URL/platform/xp-platform.git, image: $XP_REVIEW_IMAGE }
CI

# 7c) quarantine.txt — empty flaky-test quarantine (build-cop owned; testreview enforces the SLA).
cat > "$dest/quarantine.txt" <<'Q'
# quarantine.txt — flaky tests taken out of the CI gate. They still run in every pipeline
# (ctest label `quarantine`, report only) but cannot fail it.
# One test per line:  <ctest name> | <owner> | <issue URL> | <added YYYY-MM-DD> | <expires YYYY-MM-DD>
#   ctest name = unit.<pricer>.<TEST_CASE name>, e.g. unit.black_scholes.put-call parity holds
# Expiry at most 14 days after added: fix the test or delete the line by then. testreview blocks
# expired, owner-less, issue-less or unknown entries.
Q

# 8) make it a repo so guard 4c (platform/ tree hash) has a committed subtree to check.
git -C "$dest" init -q
git -C "$dest" add -A
git -C "$dest" -c user.email=gen@xp -c user.name=generator commit -q -m "generate ${name} (${ptag}, ${rtag})"

echo "generated $dest"
echo "  methods: ${methods[*]}"
echo "  platform: ${ptag}   pricers: ${rtag}"
